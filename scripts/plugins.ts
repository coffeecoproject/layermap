// Writes the Claude Code and Codex plugins, their marketplace entries and the MCP Registry entry.
// The published plugins start the server with scripts/launcher.mjs, which installs the pinned
// package from npm into LayerMap's cache; --dev writes the same plugins, started from this
// checkout, into another directory for trying them before a release.
//
// usage: node --import tsx scripts/plugins.ts [--dev <directory>]
import { readFileSync } from "node:fs";
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { buildSync } from "esbuild";
import { AGENT_MAP_NOTE } from "../src/agent/notes";
import { launcherScript } from "../src/agent/setup";

const packageRoot = fileURLToPath(new URL("../", import.meta.url));
const REPOSITORY = "https://github.com/coffeecoproject/layermap";
/** The server's MCP Registry name; npm's `mcpName` must match it for the registry to verify. */
