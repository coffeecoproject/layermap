// Claude Code starts a plugin's server without a shell, and on Windows npx is a .cmd script that
// only a shell runs. node is a real executable on every system, so the published Claude Code plugin
// starts with this script. npx installs the pinned package, or finds it installed, and names its
// command, which then runs in this process: npx and a second Node process would otherwise stay
// beside it for the whole session. The server exits when Claude Code closes its input.
const claudeServerScript = (version: string) => `// Generated by scripts/plugins.ts.
import { execFile } from "node:child_process";
import { pathToFileURL } from "node:url";

const args = [${[...npxServerArgs(version).slice(0, -1), "entry"].map((arg) => JSON.stringify(arg)).join(", ")}];
const windows = process.platform === "win32";
execFile(
  windows ? \`npx \${args.join(" ")}\` : "npx",
  windows ? [] : args,
  { shell: windows, windowsHide: true },
  (error, stdout, stderr) => {
    const entry = stdout.trim().split(/\\r?\\n/u).at(-1);
    if (error || !entry) {
      process.stderr.write(\`layermap: could not start npx: \${error?.message ?? "no entry"}\\n\${stderr}\`);
      process.exit(1);
    }
    process.argv = [process.argv[0], entry, "mcp"];
    import(pathToFileURL(entry).href);
  },
);
`;

// The code files LayerMap maps, and the same as git pathspecs.
const CODE_EXTENSIONS = ["ts", "tsx", "mts", "cts", "js", "jsx", "mjs", "cjs", "go", "py", "java"];
const CODE = CODE_EXTENSIONS.map((extension) => `'*.${extension}'`).join(" ");

// Shell shared by the Claude Code hooks: the hook's input fields, where the hook runs, the
// repository the session started in (empty outside one), and a repository's uncommitted code
// changes (empty without a commit or changes) and their fingerprint. Plain sh and git, so the hooks
// start no runtime and the plugin directory's validator can read them.
const HOOK_SHELL = String.raw`input=$(cat 2>/dev/null | tr -d '\n')
# JSON escapes a backslash as two; Windows paths (C:\\Users\\…) need them back as one.
field() { printf '%s' "$input" | sed -n "s/.*\"$1\"[[:space:]]*:[[:space:]]*\"\([^\"]*\)\".*/\1/p" | sed 's/\\\\/\\/g'; }
session=$(field session_id | tr -cd 'A-Za-z0-9_-')
[ -n "$session" ] || session=unknown
state="${"$"}{TMPDIR:-/tmp}/layermap-claude"
mkdir -p "$state" 2>/dev/null
# Claude Code's shell directory, which follows the agent's cd; the session started where the
# session-start hook first ran.
here=$(field cwd)
[ -d "$here" ] || here=$PWD
dir=$(cat "$state/$session.dir" 2>/dev/null)
[ -d "$dir" ] || dir=$here
start=$(git -C "$dir" rev-parse --show-toplevel 2>/dev/null)
# Git in a repository with no program its own config names: no fsmonitor, and no filter its
# attributes would put a changed file's content through.
repo_git() {
  _repo=$1; shift
  _blank=$(git -C "$_repo" config --name-only --get-regexp '^filter\.' 2>/dev/null |
    sed -n 's/^filter\.\(.*\)\.[^.]*$/-c filter.\1.clean= -c filter.\1.process= -c filter.\1.required=false/p' |
    sort -u | tr '\n' ' ')
  set -f
  git -C "$_repo" -c core.fsmonitor=false -c core.quotePath=false $_blank "$@"
  _status=$?
  set +f
  return $_status
}
# The name of each changed code file, and the checksum, size and name of each that still exists.
code_changes() {
  files=$(repo_git "$1" diff HEAD --name-only --no-renames -- ${CODE} 2>/dev/null) || return 0
  files=$({ printf '%s\n' "$files"
    repo_git "$1" ls-files --others --exclude-standard -- ${CODE} 2>/dev/null; } | sed '/^$/d' | sort -u)
  [ -n "$files" ] || return 0
  printf '%s\n' "$files" | sed 's/^/? /'
  printf '%s\n' "$files" | (cd "$1" && tr '\n' '\0' | xargs -0 cksum 2>/dev/null)
}
fingerprint() { printf '%s' "$1" | git hash-object --stdin 2>/dev/null; }`;

// The command hook after HOOK_SHELL, before and after each shell command: the code files the
// command changed, in the repository the session started in, the one the command runs in, those
// of the folders it names and those the session's commands changed before. Each is noted with the
// transcript's length then, for the stop hook, as an edit there. A command that ran longer than a
// minute (tests, builds, scripts) leaves time for another session to change the same work tree,
// so only the files it names count.
const COMMAND_SHELL = String.raw`call=$(field tool_use_id | tr -cd 'A-Za-z0-9_-')
[ -n "$call" ] || exit 0
before="$state/$session.$call.before"
command=$(printf '%s' "$input" | sed -nE 's/.*"command": *"(([^"\\]|\\.)*)".*/\1/p')
# Each repository on a line of its own, then its code changes, each line led by the repository.
snapshot() {
  while IFS= read -r repo; do
    [ -n "$repo" ] || continue
    printf '%s\t\n' "$repo"
    code_changes "$repo" | R=$repo awk '{ print ENVIRON["R"] "\t" $0 }'
  done
}
case "$input" in
*'"hook_event_name":"PreToolUse"'* | *'"hook_event_name": "PreToolUse"'*)
  date +%s > "$before.time" 2>/dev/null
  known=$({ printf '%s\n' "$start"
    [ "$here" = "$start" ] || git -C "$here" rev-parse --show-toplevel 2>/dev/null
    cat "$state/$session.repos" 2>/dev/null; } | sed '/^$/d' | sort -u)
  {
    printf '%s\n' "$known"
    # The repositories of the folders the command names, outside those already known.
    printf '%s\n' "$command" | sed 's/\\[nrt"]/ /g' | tr -cs 'A-Za-z0-9._/~:@+,%-' '\n' | head -n 300 |
      while IFS= read -r word; do
        case "$word" in
        "~/"*) named="$HOME/${"$"}{word#\~/}" ;;
        /*) named=$word ;;
        *) named="$here/$word" ;;
        esac
        if [ -d "$named" ]; then printf '%s\n' "$named"; elif [ -d "${"$"}{named%/*}" ]; then printf '%s\n' "${"$"}{named%/*}"; fi
      done | sort -u | head -n 20 | while IFS= read -r folder; do
        inside=
        while IFS= read -r repo; do [ -n "$repo" ] && case "$folder/" in "$repo"/*) inside=1 ;; esac; done <<KNOWN
$known
KNOWN
        [ -n "$inside" ] || git -C "$folder" rev-parse --show-toplevel 2>/dev/null
      done
  } | sed '/^$/d' | sort -u | snapshot > "$before"
  ;;
*)
  [ -f "$before" ] || exit 0
  transcript=$(field transcript_path)
  [ -f "$transcript" ] && line=$(wc -l < "$transcript" | tr -d ' ')
  started=$(cat "$before.time" 2>/dev/null)
  # Another session can change files while a command runs. A command that writes code without
  # naming the file, such as a generator or formatter, takes a few seconds; for a longer one only
  # the files it names count.
  long=0
  [ -n "$started" ] && [ $(($(date +%s) - started)) -gt 10 ] && long=1
  awk -F '\t' '$2 == "" { print $1 }' "$before" | snapshot | grep -vxF -f "$before" |
    C=$command awk -F '\t' -v line="${"$"}{line:-0}" -v long=$long '$2 != "" { name = $2; if (!sub(/^\? /, "", name)) sub(/^[0-9]+ [0-9]+ /, "", name)
      file = name; sub(/.*\//, "", file)
      if (long && !index(ENVIRON["C"], file)) next
      print line "\t" $1 "\t" name }' >> "$state/$session.edits"
  cut -f 2 "$state/$session.edits" 2>/dev/null | sort -u > "$state/$session.repos"
  rm -f "$before" "$before.time"
  ;;
esac`;

// Single-quoted for sh.
const shellQuote = (text: string) => `'${text.replaceAll("'", `'\\''`)}'`;
// Inside a JSON string, without its quotes.
const jsonText = (text: string) => JSON.stringify(text).slice(1, -1);

// The end of a sed script that unescapes the path a line's JSON gives (claude) or the JSON string in
// it gives (buddy), then prints the line.
const UNESCAPE = String.raw`:claude
s/\\\\/\\/g
p
d
:buddy
s/\\\\\\\\/\\/g
p`;

// The stop hook after HOOK_SHELL: the repositories with code changes to check, and the request to
// check them. With the session's transcript, they are the repositories with a code file the session
// edited that git still sees changed, each unless a check of that repository followed its last
// edit; a check's repository is the one the map server routes its path to. Without a transcript,
// the repository the session started in. Not the changes it started with, nor the same changes
// twice.
const STOP_SHELL = String.raw`case "$input" in *'"stop_hook_active":true'* | *'"stop_hook_active": true'*) exit 0 ;; esac
# The repository a path is in, as the map server routes a tool call's path: a relative path that
# stays in the repository the session started in is that one's, and any other is resolved from
# where the session started. Nothing outside any repository.
repository() {
  base=$start
  [ -n "$base" ] || base=$dir
  case "$1" in
  /* | [A-Za-z]:*) target=$1 ;;
  .. | ../*) target="$base/$1" ;;
  *) [ -n "$start" ] && { printf '%s\n' "$start"; return; }; target="$base/$1" ;;
  esac
  while [ ! -d "$target" ]; do
    parent=$(dirname "$target")
    [ "$parent" = "$target" ] && return
    target=$parent
  done
  git -C "$target" rev-parse --show-toplevel 2>/dev/null
}
# Lines of a number and a path, with a Windows path's slashes forward, as Git and sh take it.
slashes() { sed -E '/^[0-9]+ [A-Za-z]:/s|\\|/|g'; }
transcript=$(field transcript_path)
if [ -f "$transcript" ]; then
  # The edits and checks in the transcript, each as its line's number and the path its arguments
  # give, unescaped; grep picks out only the parts of each line these need. CodeBuddy records the
  # arguments as a JSON string inside the line, so their quotes are escaped; on a line with both,
  # the escaped ones are text the arguments hold. An edit's path is the last on its line; a check
  # without a path is given ".". Claude Code also keeps there a copy of each message it sends the
  # model, which can hold several calls on one line; only the lines of the calls themselves count.
  entries() {
    grep -nE "$1" "$transcript" 2>/dev/null | grep -vE '^[0-9]+:\{"type": *"api-request'
  }
  edits() {
    entries '"name": *"(Edit|Write|MultiEdit|NotebookEdit)"' |
      grep -oE '^[0-9]+:|"(file|notebook)_path": *"[^"]*"|\\"(file|notebook)_path\\": *\\"[^"]*' |
      awk '/^[0-9]+:$/ { line = substr($0, 1, length($0) - 1); next }
        /^"/ { plain[line] = $0; next } { escaped[line] = $0 }
        END { for (line in escaped) if (!(line in plain)) print line ":" escaped[line]
          for (line in plain) print line ":" plain[line] }' |
      sed -nE 's/^([0-9]+):"(file|notebook)_path": *"(.*)"$/\1 \3/
t claude
s/^([0-9]+):\\"(file|notebook)_path\\": *\\"(.*)\\$/\1 \3/
t buddy
d
${UNESCAPE}'
  }
  checks() {
    entries '"name": *"[^"]*project_check_changes"' |
      grep -oE '^[0-9]+:|"name": *"[^"]*project_check_changes"[^}]*' |
      awk '/^[0-9]+:$/ { line = $0; next } { print line $0 }' |
      sed -nE 's/^([0-9]+):.*"path": *"([^"]*)".*/\1 \2/
t claude
s/^([0-9]+):.*\\"path\\": *\\"(([^"\\]|\\\\\\\\)*)\\".*/\1 \2/
t buddy
s/^([0-9]+):.*/\1 ./p
d
${UNESCAPE}'
  }
  # Each code file the session edited, at its last edit: the line, its repository, its path there.
  # Each check: the line and the repository of its path.
  calls=$({
    edits | slashes | grep -E ' .*\.(${CODE_EXTENSIONS.join("|")})$' |
      awk '{ line = $1; sub(/^[0-9]+ /, ""); if (line + 0 > last[$0] + 0) last[$0] = line } END { for (file in last) print last[file], file }' |
      sort -k 2 | while read -r line file; do
        folder=${"$"}{file%/*}
        if [ "$folder" != "$seen" ]; then
          seen=$folder
          { read -r repo; read -r prefix; } <<WHERE
$(git -C "$folder" rev-parse --show-toplevel --show-prefix 2>/dev/null)
WHERE
        fi
        [ -n "$repo" ] && printf 'edit\t%s\t%s\t%s\n' "$line" "$repo" "$prefix${"$"}{file##*/}"
      done
    # The code files the session's commands changed, as the command hook noted them.
    awk -F '\t' '{ print "edit\t" $0 }' "$state/$session.edits" 2>/dev/null
    checks | slashes | while read -r line named; do
      repo=$(repository "$named")
      [ -n "$repo" ] && printf 'check\t%s\t%s\n' "$line" "$repo"
    done
  })
  # The repositories with an edit to a file git still sees changed and no check of them after it.
  due=$({
    printf '%s\n' "$calls" | awk -F '\t' '$1 == "edit" { print $3 }' | sort -u | while IFS= read -r repo; do
      { repo_git "$repo" diff HEAD --name-only --no-renames 2>/dev/null
        repo_git "$repo" ls-files --others --exclude-standard 2>/dev/null; } |
        while IFS= read -r name; do printf 'changed\t%s\t%s\n' "$repo" "$name"; done
    done
    printf '%s\n' "$calls"
  } | awk -F '\t' '$1 == "changed" { changed[$2 "\t" $3] = 1; next }
    $1 == "edit" { if (($3 "\t" $4) in changed && $2 + 0 > edit[$3] + 0) edit[$3] = $2 + 0; next }
    $1 == "check" { if ($2 + 0 > check[$3] + 0) check[$3] = $2 + 0 }
    END { for (repo in edit) if (check[repo] + 0 <= edit[repo]) print repo }' | sort)
else
  due=$start
fi
asked=
listed=
others=
while IFS= read -r repo; do
  [ -n "$repo" ] || continue
  changes=$(code_changes "$repo")
  [ -n "$changes" ] || continue
  [ "$repo" = "$start" ] && [ "$(fingerprint "$changes")" = "$(cat "$state/$session.start" 2>/dev/null)" ] && continue
  asked="$asked$repo
$changes
"
  if [ -n "$listed" ]; then listed="$listed, $repo"; else listed=$repo; fi
  [ "$repo" = "$start" ] || others=1
done <<REPOSITORIES
$due
REPOSITORIES
[ -n "$asked" ] || exit 0
asked=$(fingerprint "$asked")
[ "$asked" = "$(cat "$state/$session.checked" 2>/dev/null)" ] && exit 0
printf '%s' "$asked" > "$state/$session.checked" 2>/dev/null
reason=${shellQuote(jsonText(AGENT_STOP_CHECK))}
[ -n "$others" ] && reason="$reason "${shellQuote(jsonText(AGENT_STOP_CHECK_REPOSITORIES))}"$(printf '%s' "$listed" | sed 's/\\/\\\\/g; s/"/\\"/g')."
printf '{"decision":"block","reason":"%s"}\n' "$reason"`;

